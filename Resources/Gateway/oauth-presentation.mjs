const escapeHtml = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[character]);

// Presentation only: the existing OAuth router still validates the request,
// verifies pairing and PKCE, and issues every authorization code and token.
export function oauthPresentation({ store }) {
  const names = new Map();
  return (req, res, next) => {
    if (['/.well-known/oauth-protected-resource', '/.well-known/oauth-protected-resource/mcp'].includes(req.path)) {
      const json = res.json.bind(res);
      res.json = body => json(body && typeof body === 'object' && 'resource_name' in body
        ? { ...body, resource_name: 'Boundas Gate' } : body);
      next(); return;
    }
    if (req.path !== '/oauth/authorize') { next(); return; }
    const now = Date.now();
    for (const [id, entry] of names) if (entry.expiresAt <= now) names.delete(id);
    const clientID = req.method === 'GET' && typeof req.query.client_id === 'string' ? req.query.client_id : undefined;
    const client = clientID ? store.getClient(clientID) : undefined;
    const name = typeof client?.clientName === 'string' ? client.clientName.trim().slice(0, 120) : '';
    const prior = typeof req.body?.request_id === 'string' ? names.get(req.body.request_id) : undefined;
    const send = res.send.bind(res);
    res.send = body => {
      if (typeof body !== 'string') return send(body);
      if (body.includes('name="request_id"') && body.includes('name="pairing_code"')) {
        const requestID = body.match(/name="request_id" value="([a-f0-9]+)"/)?.[1];
        if (req.method === 'GET' && requestID && name && names.size < 1024) {
          names.set(requestID, { name, expiresAt: now + 10 * 60000 });
        }
        const displayName = name || prior?.name;
        const requester = displayName ? `<strong>${escapeHtml(displayName)}</strong>` : 'This AI app';
        body = body
          .replaceAll('Codex with ChatGPT', 'Boundas Gate')
          .replace(/<p class="sub">ChatGPT is requesting access[\s\S]*?<\/p>/,
            () => `<p class="sub">${requester} is requesting read-only access through Boundas Gate.</p>`
              + '<p class="sub">Only folders you share in the Boundas Gate app can be accessed. Newly shared folders become available automatically; you can stop sharing at any time.</p>')
          .replaceAll('Read files in this workspace', 'Read files in shared folders')
          .replaceAll('Search this workspace', 'Search shared folders')
          .replaceAll('Read Codex execution summaries', 'Read execution summaries')
          .replaceAll('The pairing code was generated by Codex on this computer.', 'Enter the pairing code from MCP Connection in the Boundas Gate app.');
      }
      body = body
        .replaceAll('Ask Codex to generate a new one.', 'Generate a new pairing code in the Boundas Gate app.')
        .replaceAll('Ask Codex to generate a new pairing code.', 'Generate a new pairing code in the Boundas Gate app.')
        .replaceAll('Ask Codex to generate a pairing code.', 'Generate a pairing code in the Boundas Gate app.')
        .replaceAll('Please reconnect from ChatGPT.', 'Please reconnect from your AI app.');
      return send(body);
    };
    next();
  };
}
